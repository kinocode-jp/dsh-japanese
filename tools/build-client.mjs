// Build: inline locale/ja/*.json into lib/client.js (ModuleLoader bundle).
// Run: node tools/build-client.mjs   (also via `npm run build`)
// Rule: the filename (without .json) is the locale namespace the dictionary
// registers, e.g. locale/ja/settings.models.json -> "settings.models".
// Missing keys fall back to English through the locale runtime's fallback
// chain, so a DSH upgrade keeps working (in English) until retranslated.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const localeRoot = join(root, 'locale');
const LANGS = [{ id: 'ja', label: '日本語' }];

// Japanese-first font stacks. DSH's built-in stacks list PingFang SC and
// Hiragino Sans GB (Simplified Chinese) ahead of every Japanese face, so
// Japanese UI text renders with Chinese glyph forms. These become root-level
// defaults: a font the user picks in Settings lands on <body> and wins, and
// clearing that field falls back here again.
const FONT_STACKS = {
  '--dsh-font-family-text':
    '"Hiragino Sans", "Hiragino Kaku Gothic ProN", "Noto Sans JP", "Noto Sans CJK JP", "Yu Gothic UI", "Yu Gothic", Meiryo, -apple-system, BlinkMacSystemFont, "Segoe UI", "Helvetica Neue", Arial, sans-serif',
  '--dsh-font-family-code':
    '"SF Mono", "JetBrains Mono", "Fira Code", Menlo, Monaco, Consolas, "Liberation Mono", "Hiragino Sans", "Hiragino Kaku Gothic ProN", "Noto Sans JP", "Yu Gothic", Meiryo, monospace',
  '--dsh-font-family-terminal':
    '"SF Mono", "JetBrains Mono", Menlo, Monaco, Consolas, "Hiragino Sans", "Hiragino Kaku Gothic ProN", "Noto Sans JP", "Yu Gothic", Meiryo, monospace',
};

function loadLang(langId) {
  const dir = join(localeRoot, langId);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => [basename(f, '.json'), JSON.parse(readFileSync(join(dir, f), 'utf8'))])
    .sort(([a], [b]) => (a < b ? -1 : 1));
}

const perLang = new Map();
for (const { id } of LANGS) {
  const entries = loadLang(id);
  for (const [ns, dict] of entries) {
    if (typeof dict !== 'object' || dict === null || Array.isArray(dict)) {
      throw new Error(`locale/${id}/${ns}.json must be a JSON object`);
    }
    for (const [k, v] of Object.entries(dict)) {
      if (typeof v !== 'string') throw new Error(`${id}/${ns}: key "${k}" must be a string`);
      if (/[\r\n]/.test(k)) throw new Error(`${id}/${ns}: key "${k}" must not contain newlines`);
    }
  }
  perLang.set(id, entries);
  const total = entries.reduce((n, [, d]) => n + Object.keys(d).length, 0);
  if (!entries.length) throw new Error(`locale/${id} has no dictionaries`);
  console.log(`${id}: ${entries.length} namespaces, ${total} keys`);
}

const DICTS = {};
for (const { id } of LANGS) {
  DICTS[id] = Object.fromEntries(perLang.get(id));
}

const banner = `// @kinocode/dsh-japanese — browser half (generated by tools/build-client.mjs; edit locale/ja/*.json, then rebuild).
// Registers 日本語 and its dictionaries. Missing keys fall back to English by the
// locale runtime's fallback chain, so new keys shipped by a DSH upgrade keep
// working (in English) until translated.`;

const out = `${banner}
window.__ModuleLoader__.load({
  id: "@kinocode/dsh-japanese",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

    //#region language list (generated)
    const LANGS = ${JSON.stringify(LANGS, null, 2)};
    //#endregion

    //#region dictionaries (generated from locale/ja/*.json)
    const DICTS = ${JSON.stringify(DICTS, null, 2)};
    //#endregion

    //#region Japanese font stacks
    const FONT_STACKS = ${JSON.stringify(FONT_STACKS, null, 2)};
    //#endregion

    /** Required services: the locale registry owned by dsh-client-locale. */
    const inject = ["locale"];

    /**
     * Client plugin body: register 日本語 and its namespace dictionaries.
     * Everything is idempotent and failure-isolated: a duplicate language
     * registration (double load) or a namespace that rejects a language must
     * not take the GUI boot down.
     * @param ctx - client root context.
     */
    function apply(ctx) {
      // Root-level font defaults: <body> variables written by the theme
      // presenter (Settings → font) override these, and clearing the setting
      // restores this stack.
      ctx.effect(() => {
        if (typeof document === "undefined") return () => {};
        const root = document.documentElement;
        for (const [name, value] of Object.entries(FONT_STACKS)) root.style.setProperty(name, value);
        return () => {
          for (const name of Object.keys(FONT_STACKS)) root.style.removeProperty(name);
        };
      }, "dsh-japanese: Japanese font stacks");

      for (const { id, label } of LANGS) {
        ctx.effect(() => {
          try {
            ctx.locale.addLanguage({ id, label, fallback: "en" });
          } catch (error) {
            if (!/already registered/.test(String(error && error.message))) throw error;
          }
          return () => {};
        }, "dsh-japanese: language " + id);
      }
      for (const [lang, namespaces] of Object.entries(DICTS)) {
        for (const [ns, dict] of Object.entries(namespaces)) {
          ctx.effect(() => {
            try {
              return ctx.locale.register(ns, { [lang]: dict });
            } catch (error) {
              if (!/already has locale/.test(String(error && error.message))) throw error;
              return () => {};
            }
          }, "dsh-japanese: " + lang + "/" + ns);
        }
      }
    }

    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  }
});
`;

writeFileSync(join(root, 'lib', 'client.js'), out, 'utf8');
console.log(`wrote lib/client.js (${(out.length / 1024).toFixed(1)} KiB)`);
